local plugin = vim.fs.dirname(vim.fs.dirname(vim.fn.fnamemodify(debug.getinfo(1, 'S').source:sub(2), ':p')))
vim.opt.rtp:prepend(plugin)
local names = require('git.buffer_names')
local root = vim.fn.tempname() .. ' URI %2f # ? [space]'
vim.fn.mkdir(root, 'p')
local function git(args)
  local argv = { 'git', '-C', root, '-c', 'user.name=Test', '-c', 'user.email=test@example.invalid', '-c', 'commit.gpgsign=false' }
  vim.list_extend(argv, args)
  local result = vim.system(argv, { text = true }):wait(); assert(result.code == 0, result.stderr)
  return vim.trim(result.stdout)
end
git({ 'init', '-qb', 'main' })
vim.fn.writefile({ 'before' }, root .. '/file.lua'); git({ 'add', '.' }); git({ 'commit', '-qm', 'First' })
vim.fn.writefile({ 'after' }, root .. '/file.lua'); git({ 'add', '.' }); git({ 'commit', '-qm', 'Second' })
local hash = git({ 'rev-parse', 'HEAD' })
require('git').setup()
local commit = require('git.features.commit')
local uri = names.commit(root, hash)
local b = commit.open({ work_tree = root })
assert(vim.api.nvim_buf_get_name(b) == uri)
local parsed_root, parsed_hash = names.parse_commit(uri)
assert(parsed_root == root and parsed_hash == hash, 'URI paths were decoded more than once')
local _, _, parent = names.parse_commit(names.commit(root, hash, 2))
assert(parent == 2 and names.commit(root, hash, 2) ~= uri, 'Merge parent identity disappeared')
-- Different views can retain independent drafts without changing normal names.
vim.api.nvim_buf_set_lines(b, 2, 3, false, { 'draft in first view' })
local draft = vim.api.nvim_buf_get_lines(b, 0, -1, false)
local duplicate = commit.open({ work_tree = root, new = true })
assert(duplicate ~= b and vim.api.nvim_buf_get_name(duplicate) == uri .. '?view=' .. duplicate)
assert(vim.deep_equal(vim.api.nvim_buf_get_lines(b, 0, -1, false), draft) and vim.bo[b].modified)
assert(not table.concat(vim.api.nvim_buf_get_lines(duplicate, 0, -1, false), '\n'):find('draft in first view', 1, true))
local duplicate_name = vim.api.nvim_buf_get_name(duplicate)
vim.api.nvim_buf_set_name(duplicate, duplicate_name .. '/renamed')
local wrote, err = pcall(vim.cmd, 'write')
assert(not wrote and tostring(err):find('without a filename', 1, true) and git({ 'rev-parse', 'HEAD' }) == hash,
  'Renaming a commit view bypassed its write target guard')
vim.api.nvim_buf_set_name(duplicate, duplicate_name)

vim.api.nvim_buf_delete(duplicate, { force = true }); vim.api.nvim_buf_delete(b, { force = true })
-- Reopen has the same URI, including quickfix entries and old serial URIs.
vim.cmd('edit ' .. vim.fn.fnameescape(uri))
assert(vim.b.git_commit == hash and vim.api.nvim_buf_get_name(0) == uri)
local clean_lines = vim.api.nvim_buf_get_lines(0, 0, -1, false)
vim.cmd('bdelete!')
local reopened = commit.open({ work_tree = root, revision = hash })
assert(vim.api.nvim_buf_get_name(reopened) == uri, 'Ordinary reopen added a duplicate ID for an unloaded buffer')
assert(not vim.bo[reopened].modified and vim.deep_equal(vim.api.nvim_buf_get_lines(reopened, 0, -1, false), clean_lines),
  'Direct reopen of an unloaded URI reentered rendering and duplicated its contents')
vim.cmd('bdelete!')
local legacy = 'git-commit://' .. root .. '/17/' .. hash
vim.cmd('edit ' .. vim.fn.fnameescape(legacy))
local legacy_root, legacy_hash = names.parse_commit(vim.api.nvim_buf_get_name(0))
assert(vim.b.git_commit == hash and legacy_root == root and legacy_hash == hash, 'Legacy commit URI no longer reloads')
vim.cmd('bdelete!')
vim.cmd('edit ' .. vim.fn.fnameescape(uri .. '?view=999'))
assert(vim.b.git_commit == hash, 'A persisted duplicate view URI no longer reloads')
vim.cmd('bdelete!')
vim.cmd('cd ' .. vim.fn.fnameescape(root)); vim.cmd('Gclog')
local items = vim.fn.getqflist(); assert(#items == 2)
assert(vim.api.nvim_buf_get_name(items[1].bufnr) == uri, 'Gclog still publishes a /0/ serial URI')
vim.cmd('cclose')
-- Output/compose names include their actual repository and target, not cwd.
local workflow = require('git.features.workflow')
local output = workflow.output(root, 'gh status', 'first')
local output_uri = names.uri('git-workflow', root, 'gh-status')
assert(vim.api.nvim_buf_get_name(output) == output_uri)
local other = workflow.output(root .. '-other', 'gh status', 'second')
assert(vim.api.nvim_buf_get_name(other) ~= output_uri and require('git.utils').get_buf_work_tree(other) == root .. '-other')
local extra = workflow.output(root, 'gh status', 'third')
assert(extra ~= output and vim.api.nvim_buf_get_name(extra) == output_uri .. '?view=' .. extra)
assert(vim.api.nvim_buf_get_lines(output, 0, -1, false)[1] == 'first')
local composer = require('git.features.pr_composer')
local opts = { ctx = { root = root, host = 'github.example', repo = 'org/repo', number = 7 },
  title = 'PR comment', submit = function() error('URI checks must not submit comments') end }
local first = composer.open(opts)
local compose_uri = names.uri('git-pr-compose', root, 'github.example/org/repo/pull/7/PR-comment')
assert(vim.api.nvim_buf_get_name(first) == compose_uri)
vim.api.nvim_buf_set_lines(first, 0, -1, false, { 'unsent draft' })
local second = composer.open(opts)
assert(vim.api.nvim_buf_get_name(second) == compose_uri .. '?view=' .. second)
assert(vim.api.nvim_buf_get_lines(first, 0, -1, false)[1] == 'unsent draft' and vim.bo[first].modified)
for _, buf in ipairs(vim.api.nvim_list_bufs()) do pcall(vim.api.nvim_buf_delete, buf, { force = true }) end
-- Non-default merge-parent views keep their comparison when reopened.
git({ 'switch', '-qc', 'side', 'HEAD^' })
vim.fn.writefile({ 'side' }, root .. '/side.lua'); git({ 'add', '.' }); git({ 'commit', '-qm', 'Side' })
local second_parent = git({ 'rev-parse', 'HEAD' })
git({ 'switch', '-q', 'main' }); git({ 'merge', '--no-ff', '-qm', 'Merge', 'side' })
local merge = git({ 'rev-parse', 'HEAD' })
local parent_buf = commit.open({ work_tree = root, revision = merge, parent = 2 })
local parent_uri = names.commit(root, merge, 2)
assert(vim.api.nvim_buf_get_name(parent_buf) == parent_uri)
vim.cmd('bdelete!'); vim.cmd('edit ' .. vim.fn.fnameescape(parent_uri))
assert(commit.model(0).parent_index == 2 and commit.model(0).base == second_parent)
for _, buf in ipairs(vim.api.nvim_list_bufs()) do pcall(vim.api.nvim_buf_delete, buf, { force = true }) end
vim.fn.delete(root, 'rf')
print('PASS: semantic buffer URIs, literal repository paths, commit reload/legacy/quickfix, and isolated duplicate commit/output/comment drafts')
