local plugin = vim.fs.dirname(vim.fs.dirname(vim.fn.fnamemodify(debug.getinfo(1, 'S').source:sub(2), ':p')))
package.path = plugin .. '/lua/?.lua;' .. plugin .. '/tests/?.lua;' .. package.path
local f = require('helpers.pr_fixture').new()
local ui = require('helpers.pr_ui').new(f)
local view = require('git.features.pr')
local function press(keys)
  vim.api.nvim_feedkeys(vim.api.nvim_replace_termcodes(keys, true, false, true), 'xt', false)
end
local function open(key, row)
  ui.source(); vim.api.nvim_win_set_cursor(0, { row or ui.row('+TWO'), 0 })
  press(key)
  ui.wait(function() return vim.bo.filetype == 'markdown' and vim.bo.buftype == 'acwrite' end)
  return vim.api.nvim_get_current_buf()
end
local function context(input) return vim.api.nvim_buf_get_lines(assert(vim.b[input].git_pr_context), 0, -1, false) end
ui.open(); ui.key('>', ui.row('M file name.txt'))
ui.wait(function() return pcall(ui.row, '+TWO') end)
-- Full key sequences must win over gc/gr without opening either menu first.
local input = open('gcn')
local lines = context(input)
assert(lines[1] == 'PR #7 · file name.txt:L2 (RIGHT)' and lines[2] == '' and lines[3]:find('Head:', 1, true))
ui.close_draft(input)
input = open('gcn', ui.row('-two'))
assert(context(input)[1] == 'PR #7 · file name.txt:L2 (LEFT)')
ui.close_draft(input)
input = open('gcn', ui.row('M file name.txt'))
assert(context(input)[1] == 'PR #7 · file name.txt (file)')
ui.close_draft(input)
input = open('gcp')
assert(context(input)[1] == 'PR #7 · Conversation')
ui.body({ 'Quick PR conversation' }); ui.send(input)
assert(#f.discussion == 1 and f.discussion[1].body == 'Quick PR conversation')
-- Visual shortcut preserves the exact RIGHT range in context and API payload.
ui.source(); vim.api.nvim_win_set_cursor(0, { ui.row('+TWO'), 0 })
press('Vjgcr')
ui.wait(function() return vim.bo.buftype == 'acwrite' and vim.bo.filetype == 'markdown' end)
input = vim.api.nvim_get_current_buf(); lines = context(input)
assert(lines[1] == 'PR #7 · file name.txt:L2-L3 (RIGHT)' and lines[2] == '')
ui.body({ 'Range review draft' }); ui.send(input)
assert(#f.reviews == 1 and f.reviews[1].state == 'PENDING' and #f.reviews[1].comments == 1)
local draft = f.reviews[1].comments[1]
assert(draft.line == 3 and draft.start_line == 2 and draft.side == 'RIGHT')
local old = view.model(ui.buf)
ui.wait(function() return view.model(ui.buf).review.pending ~= nil end)
input = open('grm') -- submits a pending review with no new summary.
assert(context(input)[1] == 'PR #7 · Submit comments')
assert(f.reviews[1].state == 'PENDING', 'Shortcut submitted before explicit save')
ui.send(input); assert(f.reviews[1].state == 'COMMENTED')
-- Published range previews/replies share the same location and blank separator.
ui.source(); ui.key('gk', ui.row(' three'))
local preview = assert(vim.b[ui.buf].git_pr_preview)
lines = vim.api.nvim_buf_get_lines(preview, 0, -1, false)
assert(lines[1]:find('file name.txt:L2-L3 (RIGHT)', 1, true) and lines[2] == '' and lines[3]:find('@viewer', 1, true))
ui.key('gc', ui.row(' three'))
input = vim.api.nvim_get_current_buf(); lines = context(input)
assert(lines[1]:find('L2-L3 (RIGHT)', 1, true) and lines[2] == '')
ui.close_draft(input)
input = open('gra'); assert(context(input)[1] == 'PR #7 · Approve')
ui.send(input); assert(f.reviews[#f.reviews].state == 'APPROVED')
input = open('grr'); assert(context(input)[1] == 'PR #7 · Request changes')
ui.body({ 'Changes requested' }); ui.send(input)
assert(f.reviews[#f.reviews].state == 'CHANGES_REQUESTED')
-- gcr outside a file rejects gracefully; gcn falls back to a PR conversation.
ui.source(); vim.api.nvim_win_set_cursor(0, { 1, 0 }); press('gcr')
assert(vim.api.nvim_get_current_buf() == ui.buf and f.notifications[#f.notifications]:find('Select a PR diff', 1, true))
input = open('gcn', 1); assert(context(input)[1] == 'PR #7 · Conversation'); ui.close_draft(input)
vim.api.nvim_buf_delete(ui.buf, { force = true }); f.cleanup()
print('PASS: direct comment/review composers, longest key sequences, visual range transport/context, blank separator, PR comments, summary-free pending submit and explicit approval/change request saves')
