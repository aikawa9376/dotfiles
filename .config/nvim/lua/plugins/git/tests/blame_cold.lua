local plugin = vim.fs.dirname(vim.fs.dirname(vim.fn.fnamemodify(debug.getinfo(1, 'S').source:sub(2), ':p')))
package.path = plugin .. '/lua/?.lua;' .. package.path
local root = vim.fn.tempname(); vim.fn.mkdir(root, 'p')
local function git(args)
  local argv = { 'git', '-C', root, '-c', 'user.name=Test', '-c', 'user.email=test@example.invalid', '-c', 'commit.gpgsign=false' }
  vim.list_extend(argv, args)
  local result = vim.system(argv, { text = true }):wait()
  assert(result.code == 0, result.stderr)
end
git({ 'init', '-qb', 'main' })
vim.fn.writefile({ 'one', 'two' }, root .. '/file.txt')
git({ 'add', '.' }); git({ 'commit', '-qm', 'base' })
vim.fn.writefile({ 'one', 'changed' }, root .. '/file.txt')
git({ 'commit', '-qam', 'change' })
vim.cmd('edit ' .. vim.fn.fnameescape(root .. '/file.txt'))
local code = vim.api.nvim_get_current_buf()
local blame = require('git.features.blame')
local buf = assert(blame.open())
assert(vim.wait(3000, function() return vim.fn.bufwinid(buf) ~= -1 end, 10))
local function press(key) assert(vim.fn.maparg(key, 'n', false, true).callback, key)() end
local ns = vim.api.nvim_create_namespace('GitBlameDiffDim')
press('gd')
assert(#vim.api.nvim_buf_get_extmarks(code, ns, 0, -1, {}) == 1, 'cold blame pin did not dim other commits')
assert(vim.fn.exists(':DiffDim') == 0, 'shared helpers must not register commands on require')
local dim = require('git.features.diffdim')
local helper = dim.select_blame
dim.setup(); dim.setup()
assert(dim.select_blame == helper, 'setup replaced the shared dim helper')
assert(#vim.api.nvim_buf_get_extmarks(code, ns, 0, -1, {}) == 1, 'setup erased the active pin')
press('gd')
assert(#vim.api.nvim_buf_get_extmarks(code, ns, 0, -1, {}) == 0, 'unpin did not clear dimming')
press('gd'); press('q')
assert(#vim.api.nvim_buf_get_extmarks(code, ns, 0, -1, {}) == 0, 'closing cold blame left dimming behind')
vim.cmd('bwipeout!')
vim.fn.delete(root, 'rf')
print('PASS: cold blame pin/unpin, deferred command registration, repeated setup and cleanup')
